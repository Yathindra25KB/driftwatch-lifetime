"""Monthly arXiv audit: new cs.CR / cs.LG papers near this study (stdlib only).

    uv run python scripts/arxiv_audit.py                 # since the last audit, writes the report
    uv run python scripts/arxiv_audit.py --since 2026-09-01 --no-state

Lists candidates only. Reading them and updating docs/related_work_addendum.md is the
arxiv-audit skill's job (.claude/skills/arxiv-audit/SKILL.md), done by a person or Claude,
never by this script. A candidate matches at least one topic group and either mentions
malware or security, or matches two topic groups.

Writes reports/arxiv_audit/<YYYY-MM-DD>.md and .json; the last audit date is kept in
reports/arxiv_audit/state.json. Exit code 0 on success, 2 if arXiv could not be read.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET  # no external entities; expat limits expansion (3.12)
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "arxiv_audit"
API = "https://export.arxiv.org/api/query?"
ATOM = {"a": "http://www.w3.org/2005/Atom"}
CATEGORIES = ("cs.CR", "cs.LG")
# topic groups of the study; phrases are matched case-insensitively in title and abstract
TOPICS: dict[str, tuple[str, ...]] = {
    "label delay": ("label delay", "delayed label", "verification latency", "label latency"),
    "analyst budget": (
        "labeling budget",
        "labelling budget",
        "annotation budget",
        "analyst budget",
        "active learning",
    ),
    "conformal / drift monitoring": (
        "conformal",
        "concept drift",
        "drift detection",
        "dataset shift",
        "distribution shift",
    ),
    "time-aware evaluation": ("temporal bias", "time-aware evaluation", "tesseract", "aging"),
}
DOMAIN = ("malware", "android app", "intrusion", "security", "windows pe", "antivirus")
PAGE = 100
PAUSE_S = 3.0  # arXiv API terms: at most one request every three seconds

Fetch = Callable[[str], bytes]


def fetch_url(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "driftwatch-arxiv-audit"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def query_url(start: int) -> str:
    cats = " OR ".join(f"cat:{c}" for c in CATEGORIES)
    phrases = sorted({p for group in TOPICS.values() for p in group})
    terms = " OR ".join(f'abs:"{p}"' for p in phrases)
    q = f"({cats}) AND ({terms})"
    params = {
        "search_query": q,
        "start": start,
        "max_results": PAGE,
        "sortBy": "submittedDate",
        "sortOrder": "descending",
    }
    return API + urllib.parse.urlencode(params)


def _text(entry: ET.Element, tag: str) -> str:
    return re.sub(r"\s+", " ", entry.findtext(f"a:{tag}", "", ATOM)).strip()


def parse(feed: bytes) -> list[dict]:
    root = ET.fromstring(feed)
    return [
        {
            "id": _text(e, "id").rsplit("/abs/", 1)[-1],
            "title": _text(e, "title"),
            "abstract": _text(e, "summary"),
            "published": _text(e, "published")[:10],
            "authors": [a.findtext("a:name", "", ATOM) for a in e.findall("a:author", ATOM)],
            "categories": [c.get("term") for c in e.findall("a:category", ATOM)],
        }
        for e in root.findall("a:entry", ATOM)
    ]


def classify(paper: dict) -> list[str]:
    """Topic groups a paper touches, or [] if it is not a candidate."""
    blob = f"{paper['title']} {paper['abstract']}".lower()
    groups = [g for g, phrases in TOPICS.items() if any(p in blob for p in phrases)]
    in_domain = any(d in blob for d in DOMAIN)
    return groups if groups and (in_domain or len(groups) >= 2) else []


def collect(since: dt.date, fetch: Fetch = fetch_url, max_pages: int = 10) -> list[dict]:
    """Candidates published on or after `since`, newest first."""
    found = []
    for page in range(max_pages):
        if page:
            time.sleep(PAUSE_S)
        papers = parse(fetch(query_url(page * PAGE)))
        for p in papers:
            if p["published"] >= since.isoformat() and (groups := classify(p)):
                found.append({**p, "topics": groups})
        if not papers or papers[-1]["published"] < since.isoformat():
            break
    return found


def render(found: list[dict], since: dt.date, today: dt.date) -> str:
    lines = [
        f"# arXiv audit {today.isoformat()}",
        "",
        f"Categories {', '.join(CATEGORIES)}; published {since.isoformat()} to {today.isoformat()};"
        f" {len(found)} candidates. Generated by `scripts/arxiv_audit.py`; candidates are not"
        " yet read. Triage with the arxiv-audit skill.",
        "",
        "| arXiv | Published | Title | Topics |",
        "|---|---|---|---|",
    ]
    for p in found:
        title = p["title"].replace("|", "/")
        lines.append(
            f"| [{p['id']}](https://arxiv.org/abs/{p['id']}) | {p['published']} | {title} |"
            f" {'; '.join(p['topics'])} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--since", type=dt.date.fromisoformat, help="default: last audit date")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--no-state", action="store_true", help="do not update state.json")
    args = ap.parse_args(argv)
    today = dt.datetime.now(dt.UTC).date()
    state_file = args.out / "state.json"
    state = json.loads(state_file.read_text("utf-8")) if state_file.exists() else {}
    since = args.since or dt.date.fromisoformat(state.get("last_audit", "2026-10-01"))
    try:
        found = collect(since, fetch_url)
    except (OSError, ET.ParseError) as exc:
        print(f"arXiv could not be read: {exc}", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / f"{today.isoformat()}.md").write_text(render(found, since, today), "utf-8")
    (args.out / f"{today.isoformat()}.json").write_text(json.dumps(found, indent=2), "utf-8")
    if not args.no_state:
        state_file.write_text(json.dumps({"last_audit": today.isoformat()}) + "\n", "utf-8")
    print(f"{len(found)} candidates since {since.isoformat()}: {args.out / today.isoformat()}.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
