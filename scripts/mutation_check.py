"""Mutation checks for the slicer and the constraints: the kill matrix.

For every mutant in tests/slicer_mutants.py this runs the real constraint and slicer test
suites in a subprocess with that one mutant applied (tests/mutation_plugin.py) and requires
the run to fail. The unmutated baseline must pass. A mutant that survives means a leakage
rule has no test that would notice it being broken.

    uv run python scripts/mutation_check.py              # all mutants, writes the report
    uv run python scripts/mutation_check.py shift_boundary c1_non_strict
    uv run python scripts/mutation_check.py --no-report  # exit code only

Full pytest output per mutant goes to results/mutation/ (not committed); the summary table
goes to reports/mutation_matrix.md.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
SUITES = [
    "tests/test_constraints.py",
    "tests/test_slicer.py",
    "tests/test_slicer_properties.py",
    "tests/test_slicer_cached.py",
    "tests/test_slicer_review_fixes.py",
]


def run_suites(mutant: str | None) -> dict:
    env = os.environ.copy()
    env["PYTHONPATH"] = os.pathsep.join(filter(None, [str(TESTS), env.get("PYTHONPATH", "")]))
    env["HYPOTHESIS_PROFILE"] = "mutants"
    env.pop("DRIFTWATCH_MUTANT", None)
    if mutant:
        env["DRIFTWATCH_MUTANT"] = mutant
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-p", "mutation_plugin"]
    cmd += ["--maxfail=60", "-m", "not slow", *SUITES]
    started = time.perf_counter()
    proc = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True)
    output = proc.stdout + proc.stderr
    failing = sorted(set(re.findall(r"^(?:FAILED|ERROR) (\S+)", proc.stdout, re.M)))
    tail = [ln for ln in proc.stdout.splitlines() if ln.strip()][-1:]
    return {
        "mutant": mutant or "(none: baseline)",
        "exit": proc.returncode,
        "failing": failing,
        "summary": tail[0] if tail else "",
        "seconds": time.perf_counter() - started,
        "output": output,
    }


def short(test_id: str) -> str:
    return test_id.replace("tests/", "").replace("::", " :: ")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("mutants", nargs="*", help="mutant names (default: all)")
    parser.add_argument("--no-report", action="store_true", help="do not write the markdown report")
    parser.add_argument("--out", type=Path, default=ROOT / "reports" / "mutation_matrix.md")
    parser.add_argument("--log-dir", type=Path, default=ROOT / "results" / "mutation")
    args = parser.parse_args(argv)

    sys.path.insert(0, str(TESTS))
    from slicer_mutants import MUTANTS

    unknown = set(args.mutants) - set(MUTANTS)
    if unknown:
        parser.error(f"unknown mutants: {sorted(unknown)}")
    names = args.mutants or list(MUTANTS)

    args.log_dir.mkdir(parents=True, exist_ok=True)
    baseline = run_suites(None)
    print(f"baseline: exit {baseline['exit']}, {baseline['summary']}")
    (args.log_dir / "baseline.txt").write_text(baseline["output"], encoding="utf-8")
    rows, survivors = [], []
    for name in names:
        result = run_suites(name)
        (args.log_dir / f"{name}.txt").write_text(result["output"], encoding="utf-8")
        killed = result["exit"] != 0
        if not killed:
            survivors.append(name)
        print(
            f"{'KILLED  ' if killed else 'SURVIVED'} {name:<22} "
            f"{result['summary']}  ({result['seconds']:.0f} s)"
        )
        for test_id in result["failing"][:3]:
            print(f"           failing: {short(test_id)}")
        rows.append((name, MUTANTS[name].breaks, killed, result))

    ok = baseline["exit"] == 0 and not survivors
    if not args.no_report:
        lines = [
            "# Slicer mutation checks (kill matrix)",
            "",
            "Generated by `uv run python scripts/mutation_check.py`. Each mutant breaks one "
            "rule of the slicer or the constraints; the real constraint, slicer, property and "
            "cache suites then run and must fail. Baseline = no mutant.",
            "",
            f"Baseline: exit {baseline['exit']} ({baseline['summary']}).",
            "",
            "| Mutant | Rule broken | Result | Failing tests | First failing tests |",
            "|---|---|---|---|---|",
        ]
        for name, breaks, killed, result in rows:
            first = "<br>".join(short(t) for t in result["failing"][:3]) or "-"
            verdict = "KILLED" if killed else "**SURVIVED**"
            lines.append(f"| {name} | {breaks} | {verdict} | {len(result['failing'])} | {first} |")
        lines += ["", f"Result: {'all mutants killed' if ok else 'FAILED: see above'}.", ""]
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {args.out}")
    if baseline["exit"] != 0:
        print("baseline is not green; mutation results are meaningless", file=sys.stderr)
    if survivors:
        print(f"SURVIVED: {survivors}", file=sys.stderr)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
