"""Window options for ADR-0005, derived from slot counts only (no features, no models).

    uv run python scripts/window_options.py            # both datasets, writes reports/

Writes reports/tables/window_segments_<dataset>.csv (usable runs per ratio),
reports/tables/window_options_<dataset>.csv (windows per candidate) and
reports/window_options.md. Re-run when the data caches or ADR-0004 change.
"""

from __future__ import annotations

import argparse
import itertools
import logging
from pathlib import Path

import pandas as pd

from driftwatch.data.presets import cached_source
from driftwatch.data.window_options import candidate_windows, segment_table

ROOT = Path(__file__).resolve().parents[1]
RATIOS = (0.10, 0.05, 0.20)
MIN_MALWARE = (30, 50, 100)
GRID = {
    "lamda": {"nT": (3, 4), "nE": (6, 12), "stride": (1, 3, 6)},
    "bodmas": {"nT": (3, 4), "nE": (4, 5, 6, 8), "stride": (1, 2, 3)},
}


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append(
            "| " + " | ".join(f"{v:.2f}" if isinstance(v, float) else str(v) for v in row) + " |"
        )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path("data"))
    parser.add_argument("--out", type=Path, default=ROOT / "reports")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.WARNING)
    tables = args.out / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    sections = [
        "# Window options (ADR-0005 input)",
        "",
        "Generated by `uv run python scripts/window_options.py` from the cached slot counts "
        "only (ADR-0004 slots, placeholder-dated BODMAS benign rows excluded). No features "
        "were loaded and no model was trained. `below target` counts slots whose raw malware "
        "share is already under the ratio (cap and flag: they keep all rows).",
        "",
    ]
    for dataset, grid in GRID.items():
        source = cached_source(dataset, args.root)
        seg_rows, opt_rows = [], []
        for ratio, m in itertools.product(RATIOS, MIN_MALWARE):
            for seg in segment_table(source, ratio=ratio, min_malware=m):
                seg_rows.append({"ratio": ratio, "min_malware": m, **seg})
        for ratio, m in itertools.product(RATIOS, (50,)):
            for nT, nE, stride in itertools.product(grid["nT"], grid["nE"], grid["stride"]):
                opt_rows.append(
                    candidate_windows(
                        source, nT=nT, nE=nE, stride=stride, ratio=ratio, min_malware=m
                    )
                )
        segs, opts = pd.DataFrame(seg_rows), pd.DataFrame(opt_rows)
        segs.to_csv(tables / f"window_segments_{dataset}.csv", index=False, lineterminator="\n")
        opts.to_csv(tables / f"window_options_{dataset}.csv", index=False, lineterminator="\n")

        sections += [f"## {dataset.upper()} ({source.provenance()['length']} slots)", ""]
        headline = segs[(segs["ratio"] == 0.10) & (segs["min_malware"] == 50)]
        keep = ["first", "last", "n_slots", "n_below_target", "min_malware_kept"]
        sections += ["### Usable runs at ratio 0.10, M = 50", "", md(headline[keep]), ""]
        by_ratio = (
            segs[(segs["min_malware"] == 50)]
            .groupby("ratio")
            .agg(
                usable_slots=("n_slots", "sum"),
                below_target=("n_below_target", "sum"),
                longest_run=("n_slots", "max"),
                runs=("n_slots", "size"),
            )
            .reset_index()
        )
        sections += ["### Usable slots by target ratio (M = 50)", "", md(by_ratio), ""]
        by_m = (
            segs[segs["ratio"] == 0.10]
            .groupby("min_malware")
            .agg(usable_slots=("n_slots", "sum"), longest_run=("n_slots", "max"))
            .reset_index()
        )
        sections += ["### Usable slots by size gate (ratio 0.10)", "", md(by_m), ""]
        view = opts[opts["ratio"] == 0.10][
            ["nT", "nE", "stride", "n_windows", "n_eval_slots_distinct", "eval_reuse"]
        ]
        sections += ["### Windows per candidate (ratio 0.10, M = 50)", "", md(view), ""]
    (args.out / "window_options.md").write_text("\n".join(sections), encoding="utf-8")
    print(f"wrote {args.out / 'window_options.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
