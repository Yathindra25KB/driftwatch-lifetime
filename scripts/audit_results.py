"""Audit results/ for runs that are not (or no longer) evidence. Reads only; deletes nothing.

    uv run python scripts/audit_results.py                  # writes docs/results_audit.md
    uv run python scripts/audit_results.py --results results --out docs/results_audit.md

``results/`` is never committed, so this table is the record of what is on the researcher's
disk. For every top-level folder it counts the finished runs (``run.json``) and failed runs
(``run_failed.json``) at any depth, lists the code versions they carry, and flags:

- **dirty**: the run was made on a working tree with uncommitted changes (``-dirty`` or
  ``unknown`` code version), so no commit reproduces it;
- **smoke**: ``max_windows`` was set (a timing run, never evidence) or the folder name says so;
- **several versions**: more than one code version in one folder, which a grid refuses for
  evidence (``driftwatch grid`` pins one commit); an old baseline folder may show this when it
  was rerun after a code change.

A folder with no ``run.json`` is tooling output (benchmarks, canaries, mutation logs). Whether a
flagged folder is superseded and may be deleted is the researcher's decision; this script
only lists.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SMOKE_WORDS = ("smoke",)


@dataclass
class Row:
    folder: str
    n_complete: int = 0
    n_failed: int = 0
    n_smoke: int = 0
    n_dirty: int = 0
    versions: set[str] = field(default_factory=set)
    n_other_files: int = 0

    @property
    def flags(self) -> list[str]:
        out = []
        if self.n_dirty:
            out.append("dirty")
        if self.n_smoke or any(w in self.folder for w in SMOKE_WORDS):
            out.append("smoke")
        if len(self.versions) > 1:
            out.append("several versions")
        if self.n_failed:
            out.append("has failed runs")
        if not (self.n_complete or self.n_failed):
            out.append("tooling output (no run.json)")
        return out


def is_dirty(version: str | None) -> bool:
    return version is None or version == "unknown" or version.endswith("-dirty")


def src_changes_since(version: str, repo: Path = ROOT) -> int | None:
    """Files under src/ that differ between ``version`` and HEAD; None if git cannot say."""
    base = version.removesuffix("-dirty")
    out = subprocess.run(
        ["git", "-C", str(repo), "diff", "--name-only", base, "HEAD", "--", "src"],
        capture_output=True, text=True, encoding="utf-8", check=False,
    )  # fmt: skip
    return len(out.stdout.split()) if out.returncode == 0 else None


def collect(results: Path) -> list[Row]:
    rows = []
    for top in sorted(p for p in results.iterdir() if p.is_dir()):
        row = Row(top.name)
        for path in top.rglob("*"):
            if path.name == "run.json":
                rec = json.loads(path.read_text(encoding="utf-8"))
                row.n_complete += rec.get("status") == "complete"
                row.n_failed += rec.get("status") not in (None, "complete")
                v = rec.get("code_version")
                row.versions.add(str(v))
                row.n_dirty += is_dirty(v)
                row.n_smoke += rec.get("max_windows") is not None
            elif path.name == "run_failed.json":
                row.n_failed += 1
            elif path.is_file() and path.suffix in {".csv", ".json", ".txt", ".yaml", ".log"}:
                row.n_other_files += 1
        rows.append(row)
    return rows


def _changed(version: str) -> str:
    n = src_changes_since(version)
    return "?" if n is None else str(n)


def render(rows: list[Row]) -> str:
    lines = [
        "# Results audit",
        "",
        "Generated by `scripts/audit_results.py`. `results/` is never committed; this table is "
        "the record of what is on disk. Nothing was deleted. Whether a flagged folder is "
        "superseded is the researcher's decision.",
        "",
        "| Folder | Finished runs | Failed runs | Code versions (src files changed since) | "
        "Flags |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        versions = (
            ", ".join(f"{v} ({_changed(v)})" for v in sorted(r.versions)) if r.versions else "none"
        )
        lines.append(
            f"| {r.folder} | {r.n_complete} | {r.n_failed} | {versions} | "
            f"{'; '.join(r.flags) or 'none'} |"
        )
    lines += [
        "",
        "The number in brackets is how many files under `src/` differ between that code "
        "version and HEAD (`?` when git cannot resolve the version). A run on code that has "
        "since changed is not necessarily wrong: the regression tests and the clean-clone "
        "reproduction decide that. It is the signal to look.",
        "",
        "Flags: **dirty** = made on an uncommitted tree; **smoke** = a timing run, never "
        "evidence; **several versions** = more than one code version in the folder; "
        "**tooling output** = no run record (benchmarks, canaries, mutation logs).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "results_audit.md")
    args = ap.parse_args(argv)
    if not args.results.is_dir():
        print(f"{args.results}: no such folder")
        return 1
    text = render(collect(args.results))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("utf-8"))
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
